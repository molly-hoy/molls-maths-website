"""
Build the worksheet PDFs
========================

Run from the project folder:

    python3 worksheets-src/build.py              # build every worksheet
    python3 worksheets-src/build.py angles       # only slugs containing "angles"
    python3 worksheets-src/build.py --publish    # build, then put them on the site

What it does:
  1. Finds every file in worksheets-src/topics/. A file makes one worksheet
     (META + build) or several (a SHEETS list of (META, build) pairs).
  2. Builds each PDF into worksheets-src/output/<slug>.pdf, plus a pupil
     copy with no answer pages in worksheets-src/output/pupil/<slug>.pdf.
     This does NOT change the website, so you can check the PDFs first.
  3. Marks finished worksheets as "done" in worksheet-list.csv.

With --publish it also:
  4. Copies the PDFs into public/worksheets/. Anything in /public is copied
     to the live site as-is, so they become downloadable at
     /worksheets/<slug>.pdf (and /worksheets/pupil/<slug>.pdf).
  5. Rewrites src/data/worksheets.js, the list the Worksheets page reads.
     Don't edit that file by hand.

Each worksheet's title, topic and level come from worksheet-list.csv, so
to retag a worksheet, change it there and build again.

Needs Python 3 and the reportlab library (pip install reportlab).
"""
import csv
import importlib
import json
import pkgutil
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))

from engine.layout import Worksheet  # noqa: E402
import topics  # noqa: E402

OUT_DIR = HERE / "output"                       # PDFs are built here
PUPIL_DIR = OUT_DIR / "pupil"                   # pupil copies (no answers) go here
SITE_DIR = ROOT / "public" / "worksheets"       # ...and both are copied here by --publish
MANIFEST = ROOT / "src" / "data" / "worksheets.js"
LIST = HERE / "worksheet-list.csv"              # the master list: topic and level live here


def read_list():
    with LIST.open(encoding="utf-8") as f:
        return list(csv.DictReader(f))


def write_list(rows):
    """Tick off finished worksheets in the master list."""
    for r in rows:
        r["status"] = "done" if (OUT_DIR / f"{r['slug']}.pdf").exists() else "to do"
    with LIST.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)


def all_sheets():
    """Every (META, build) pair from every file in topics/."""
    for info in pkgutil.iter_modules(topics.__path__):
        mod = importlib.import_module(f"topics.{info.name}")
        if hasattr(mod, "SHEETS"):
            yield from mod.SHEETS
        else:
            yield mod.META, mod.build


def publish(rows, built):
    """Copy PDFs to the site and rewrite the list the Worksheets page reads."""
    (SITE_DIR / "pupil").mkdir(parents=True, exist_ok=True)
    by_slug = {r["slug"]: r for r in rows}
    entries = []
    for slug in built:
        shutil.copy2(OUT_DIR / f"{slug}.pdf", SITE_DIR / f"{slug}.pdf")
        shutil.copy2(PUPIL_DIR / f"{slug}.pdf", SITE_DIR / "pupil" / f"{slug}.pdf")
        r = by_slug[slug]
        entries.append({"title": r["title"], "slug": slug, "topic": r["topic"], "level": r["level"],
                        "file": f"worksheets/{slug}.pdf",              # with answers
                        "pupilFile": f"worksheets/pupil/{slug}.pdf"})  # without answers
    entries.sort(key=lambda e: e["title"].lower())
    MANIFEST.write_text(
        "/* ==========================================================================\n"
        "   Worksheets list (AUTO-GENERATED by worksheets-src/build.py --publish)\n"
        "   --------------------------------------------------------------------------\n"
        "   One entry per PDF in public/worksheets/. The Worksheets page reads this to\n"
        "   show the cards, the filters and the search. \"file\" is the full worksheet\n"
        "   with answers; \"pupilFile\" is the same worksheet without the answer pages.\n"
        "   Don't edit by hand.\n"
        "   ========================================================================== */\n"
        f"export const WORKSHEETS = {json.dumps(entries, indent=2, ensure_ascii=False)};\n",
        encoding="utf-8",
    )
    print(f"  published {len(entries)} worksheets to the site")


def main(args):
    do_publish = "--publish" in args
    words = [a for a in args if not a.startswith("--")]
    only = words[0] if words else None

    PUPIL_DIR.mkdir(parents=True, exist_ok=True)
    rows = read_list()
    by_slug = {r["slug"]: r for r in rows}
    built, seen = [], set()
    for meta, build in all_sheets():
        slug = meta["slug"]
        assert slug not in seen, f"two worksheets use the slug {slug}"
        seen.add(slug)
        row = by_slug.get(slug)
        if row is None:
            print(f"  ! {slug} is not in worksheet-list.csv (check the slug)")
            continue
        pdf = OUT_DIR / f"{slug}.pdf"
        if only is None or only in slug:
            ws = Worksheet(row["title"], level=row["level"])
            build(ws)
            pages = ws.save(str(pdf), pupil_path=str(PUPIL_DIR / f"{slug}.pdf"))
            print(f"  built {pdf.name}  ({pages} pages)")
        if pdf.exists() and (PUPIL_DIR / f"{slug}.pdf").exists():
            built.append(slug)

    write_list(rows)
    done = sum(r["status"] == "done" for r in rows)
    print(f"  {done} of {len(rows)} worksheets done")
    if do_publish:
        publish(rows, built)


if __name__ == "__main__":
    main(sys.argv[1:])
